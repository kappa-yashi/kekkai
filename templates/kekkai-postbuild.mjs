// kekkai-postbuild.mjs — runs after `astro build`.
//   "build": "astro build && node scripts/kekkai-postbuild.mjs"
//
// 1. Writes dist/_headers from the HTML that was actually built: one CSP block per
//    document path, so no CSP sits under /* and no new page ships without one.
// 2. Writes dist/version.txt (no-store) and lets you stamp <meta name="build"> from the same values.
// 3. Strips comments from served config files (a CMS config.yml is public).
// 4. Fails if public/_headers exists: two sources of truth, one overwrites the other.
//
// Edit the CONFIG block. Everything else can stay as it is.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, rmSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { execSync } from 'node:child_process';

// ───────────────────────── CONFIG ─────────────────────────
const DIST = 'dist';
const ADMIN = process.env.KEKKAI_ADMIN || '';            // CMS folder name (unguessable). Empty = no CMS.
const MEDIA_HOSTS = [];                                   // e.g. ['https://media.example.com'] for media-src
const FRAME_HOSTS = [];                                   // e.g. ['https://www.youtube-nocookie.com'] for frame-src
const CONNECT_HOSTS = [];                                 // extra connect-src origins, if any
const HSTS = 'max-age=31536000; includeSubDomains';       // add "; preload" only as a deliberate decision
const REFERRER = 'strict-origin-when-cross-origin';       // or 'no-referrer'
const STRIP_CONFIG_COMMENTS = true;                       // comments in served .yml/.toml are public
// ─────────────────────────────────────────────────────────

if (existsSync('public/_headers')) { console.error('kekkai-postbuild: public/_headers exists — delete it; _headers is generated here.'); process.exit(1); }

const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]);
const files = walk(DIST);
const rel = (f) => '/' + relative(DIST, f).split(sep).join('/');

// Document routes = every HTML file, as the path the browser requests.
const docPaths = files.filter((f) => f.endsWith('.html')).map(rel)
  .filter((p) => !ADMIN || !p.startsWith(`/${ADMIN}/`))
  .map((p) => p.endsWith('/index.html') ? p.slice(0, -'index.html'.length) : p);

// Group routes: top-level files stay explicit, folders collapse to /folder/*.
const groups = new Set();
for (const p of docPaths) {
  const segs = p.split('/').filter(Boolean);
  if (segs.length <= 1) groups.add(p === '/' ? '/' : p);
  else groups.add(`/${segs[0]}/*`);
}
// A folder index (/posts/) is matched by /posts/* already — never add both, or the page gets two policies.
for (const p of docPaths) { const segs = p.split('/').filter(Boolean); if (segs.length === 1 && p.endsWith('/') && groups.has(`/${segs[0]}/*`)) groups.delete(p); }

const list = (base, extra) => [base, ...extra].join(' ');
const DOC_CSP = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  list("connect-src 'self'", CONNECT_HOSTS),
  list("media-src 'self'", MEDIA_HOSTS),
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  FRAME_HOSTS.length ? list('frame-src', FRAME_HOSTS) : "frame-src 'none'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

// A Git-based CMS needs its Git host; adjust for GitLab/Gitea. Scoped to the CMS path only.
const CMS_CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https://avatars.githubusercontent.com https://raw.githubusercontent.com https://*.githubusercontent.com",
  "font-src 'self' data:",
  "connect-src 'self' https://api.github.com https://github.com https://raw.githubusercontent.com https://*.githubusercontent.com",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'self' https://github.com",
  "frame-ancestors 'none'",
].join('; ');

const COMMON = [
  `Strict-Transport-Security: ${HSTS}`,
  'X-Frame-Options: DENY',
  'X-Content-Type-Options: nosniff',
  `Referrer-Policy: ${REFERRER}`,
  'Permissions-Policy: accelerometer=(), autoplay=(), camera=(), display-capture=(), encrypted-media=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), midi=(), payment=(), usb=(), interest-cohort=()',
  'Cross-Origin-Opener-Policy: same-origin',
  'Cross-Origin-Resource-Policy: same-origin',
  'X-DNS-Prefetch-Control: off',
  '! Access-Control-Allow-Origin',
];

let out = '# generated by kekkai-postbuild — do not edit by hand\n\n';
out += '/version.txt\n  Cache-Control: no-store\n\n';
out += '/_astro/*\n  Cache-Control: public, max-age=31536000, immutable\n\n';
out += '/fonts/*\n  Cache-Control: public, max-age=31536000, immutable\n\n';
out += '/*\n' + COMMON.map((h) => `  ${h}`).join('\n') + '\n\n';
for (const g of [...groups].sort()) out += `${g}\n  Content-Security-Policy: ${DOC_CSP}\n\n`;
if (ADMIN) {
  out += `/${ADMIN}/*\n  Content-Security-Policy: ${CMS_CSP}\n  Cache-Control: no-store\n  X-Robots-Tag: noindex, nofollow, noarchive\n  Cross-Origin-Opener-Policy: same-origin-allow-popups\n\n`;
}
writeFileSync(join(DIST, '_headers'), out);

// Build fingerprint.
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
let sha = process.env.CF_PAGES_COMMIT_SHA || process.env.GITHUB_SHA || '';
if (!sha) { try { sha = execSync('git rev-parse HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { sha = ''; } }
const stamp = `${pkg.version || '0.0.0'}${sha ? ' ' + sha.slice(0, 7) : ''}`;
writeFileSync(join(DIST, 'version.txt'), `${stamp}\nbuilt ${new Date().toISOString().slice(0, 10)}\n`);

// Comments in served config files are read by everyone.
if (STRIP_CONFIG_COMMENTS) {
  for (const f of files.filter((f) => /\.(ya?ml|toml)$/i.test(f))) {
    const src = readFileSync(f, 'utf8');
    const stripped = src.split('\n').filter((l) => !/^\s*#/.test(l)).map((l) => l.replace(/\s+#(?![^"']*["'][^"']*$).*$/, '')).join('\n');
    if (stripped !== src) writeFileSync(f, stripped);
  }
}

// Belt and braces: an old admin folder must never deploy again.
for (const old of ['admin', 'cms']) if (old !== ADMIN && existsSync(join(DIST, old))) rmSync(join(DIST, old), { recursive: true, force: true });

console.log(`kekkai-postbuild: ${groups.size} CSP group(s), ${docPaths.length} document(s)${ADMIN ? ', CMS block' : ''}, version ${stamp}`);
